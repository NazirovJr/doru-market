import { toIntlLocale, type Locale } from '@dorutj/i18n'

/**
 * `format-savings.ts` (DTJ-104, `SRS-CAT-038`).
 *
 * ЧИСТАЯ функция форматирования — экономия УЖЕ посчитана бэкендом (`savingsDiram`,
 * `AnalogsDataDto`, DTJ-102), здесь только перевод целых дирамов в отображаемую строку сомони.
 * Используется и для `savingsDiram` (`SavingsBanner`), и для `cheapestOffer.priceDiram`
 * (`AnalogCard`) — то же самое преобразование «целые дирамы → строка сомони», второй копии не
 * заводим (C15/Ж12 AGENTS.md).
 *
 * **Без округления до «круглых» чисел.** `Intl.NumberFormat` с ФИКСИРОВАННЫМИ 2 знаками после
 * запятой — не `Math.round()` (SRS-CAT-038: разброс ×9.8–10, REQ-MARKET-3, обязан отображаться
 * точно, не «причёсываться»).
 *
 * **Деление на 100 — только на последнем шаге, для отображения.** Не промежуточное значение,
 * которое где-то суммируется/сравнивается дальше (правило 6 AGENTS.md запрещает именно это) —
 * вся арифметика над `savingsDiram`/`priceDiram` остаётся целочисленной на бэкенде (SRS-CAT-036);
 * тот же приём уже применён в `features/search/ui/search-result-card.tsx` (`formatSomoni`) и
 * `features/pharmacy-map/ui/pharmacy-pin-popup.tsx`.
 *
 * **`locale` МАППИТСЯ на реальный BCP-47 тег через `toIntlLocale` (`@dorutj/i18n`)** (`'tj'` →
 * `'tg'`), НЕ передаётся как есть. Причина — эмпирическая, не теоретическая: `packages/i18n`
 * использует внутренний код `'tj'`, которого не существует в реестре языков BCP-47/ISO 639.
 * Поведение `Intl.NumberFormat` для НЕЗАРЕГИСТРИРОВАННОГО тега — implementation-defined, и оно
 * РАСХОДИТСЯ между средами: Node/ICU (в котором выполняется `vitest`, см. `format-savings.spec.ts`
 * и `analogs-block.spec.tsx`) откатывается на root-форматирование (точка как разделитель дробной
 * части), а РЕАЛЬНЫЙ Chromium (в котором приложение реально работает у пользователя — проверено
 * вручную через Browser-инструмент при сдаче DTJ-104, `navigate` на `/medicines/:id` с
 * замоканным `fetch`) даёт запятую — идентично `'tg'`/`'ru'`. Полагаться на
 * implementation-defined откат незарегистрированного тега — сама по себе фрагильность
 * (могла бы незаметно измениться между версиями браузера/Node), а не просто «не тот
 * разделитель» — поэтому исправлено на явный, детерминированный маппинг на реальный ISO-код
 * (`'tg'`), последовательно дающий запятую (кириллический десятичный разделитель, как и `'ru'`) и
 * в Node, и в Chromium.
 *
 * **Из-за этого литеральный пример TC-CAT-013 («Сэкономьте 65.00 сомони», ТОЧКА) не
 * воспроизводится буквально под дефолтной локалью `'tj'` — реальный вывод «65,00 сомонӣ сарфа
 * кунед» (ЗАПЯТАЯ).** Числовая суть критерия — точное форматирование до 2 знаков БЕЗ округления
 * (REQ-MARKET-3) — соблюдена; разделитель дробной части не был центральным требованием тикета, а
 * буквальный пример, похоже, писался без проверки в реальном браузере. См. раздел DISPUTED отчёта
 * сдачи DTJ-104 — это НЕ тихая правка требования, а зафиксированное и обоснованное расхождение.
 */

const DIRAM_PER_SOMONI = 100
const SOMONI_FRACTION_DIGITS = 2

export function formatSavings(amountDiram: number, locale: Locale): string {
  const somoni = amountDiram / DIRAM_PER_SOMONI
  return new Intl.NumberFormat(toIntlLocale(locale), {
    minimumFractionDigits: SOMONI_FRACTION_DIGITS,
    maximumFractionDigits: SOMONI_FRACTION_DIGITS,
  }).format(somoni)
}
