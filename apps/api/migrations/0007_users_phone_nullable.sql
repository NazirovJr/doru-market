-- Снятие NOT NULL с `users.phone_number`. Эволюционная миграция, обратно
-- совместимая с DTJ-014 (OTP-флоу, все существующие строки имеют phone).
--
-- Причина (SRS-API-031 шаг 9, DTJ-027 §«Риски»):
--   Telegram TWA-путь НЕ ИМЕЕТ телефона на момент первого входа — клиент
--   указывает телефон позже (при оформлении первого заказа, отдельный
--   сценарий вне scope DTJ-027). Изначально DDL 11-database-schema.md
--   давал `phone_number NOT NULL` без оговорок (DTJ-014, OTP-only flow);
--   расхождение со спецификацией auth всплыло только при реализации
--   Telegram-пути в DTJ-027.
--
-- Компромисс vs альтернативы:
--   - Альтернатива A (отдельная `telegram_only_users` без строки `users`):
--     два разных типа «пользователя без телефона» в системе — нарушает C15
--     (нет второго явного требования на разные абстракции).
--   - Альтернатива B (UUID-как-строка-плейсхолдер для `phone_number`):
--     нарушает `PhoneNumber.parse` (DTJ-008) и `unique_phone_per_tenant`.
--   ВЫБРАНО: nullable-поле (минимальное изменение).
--
-- Совместимость с `unique_phone_per_tenant`:
--   Postgres-стандарт: UNIQUE-индекс ИГНОРИРУЕТ строки, где хотя бы один
--   из индексируемых столбцов IS NULL. Несколько Telegram-пользователей
--   с `phone_number = NULL` в одном тенанте НЕ конфликтуют на этом
--   constraint. Все существующие строки (с реальным phone) защищены
--   как и раньше.
-- =============================================================================

ALTER TABLE users
  ALTER COLUMN phone_number DROP NOT NULL;
