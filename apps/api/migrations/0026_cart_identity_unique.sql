-- КОНТЕКСТ: `ResolveOrCreateCartUseCase` (DTJ-226) резолвит/идемпотентно создаёт корзину по
-- владельцу (`customer_id`/`session_token`) через `pg_advisory_xact_lock` в
-- `DrizzleCartIdentityRepository` — advisory-лок КОРРЕКТНО сериализует конкурентные вызовы
-- ЭТОГО адаптера, но инвариант «одна корзина на клиента в тенанте» держится лишь до тех пор,
-- пока КАЖДЫЙ будущий путь вставки в `cart` вспомнит про этот лок. `DTJ-227` (checkout) уже
-- пишет в эту же таблицу. Индекс — гарантия на уровне схемы, независимая от дисциплины
-- вызывающего кода; advisory-лок остаётся (превращает гонку в ожидание вместо ошибки
-- `23505 unique_violation`, лучший UX) — индекс и лок дополняют друг друга, не дублируют.
--
-- ЧАСТИЧНЫЕ (не полные `UNIQUE(tenant_id, customer_id)`) — потому что у гостевой корзины
-- `customer_id IS NULL` (и наоборот у клиентской `session_token IS NULL`), а Postgres не
-- считает `NULL`ы равными друг другу для целей уникальности: без `WHERE ... IS NOT NULL`
-- индекс пропустил бы СКОЛЬКО УГОДНО гостевых корзин с `customer_id = NULL` в одном тенанте.
--
-- Идемпотентна (`IF NOT EXISTS`) — прогоняется повторно без ошибки. Если `CREATE INDEX`
-- упадёт на дублях в целевой БД — это не помеха применению миграции, а сигнал о реальном
-- дефекте данных (две корзины уже созданы на одного клиента до этой правки); проверено на
-- `dorutj_test2` перед применением — дублей 0 (см. отчёт сдачи DTJ-226).
-- =====================================================================================

CREATE UNIQUE INDEX IF NOT EXISTS cart_tenant_customer_uq ON cart (tenant_id, customer_id) WHERE customer_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS cart_tenant_session_uq ON cart (tenant_id, session_token) WHERE session_token IS NOT NULL;
