-- значения, вводит новое.
--
-- ОТДЕЛЬНЫЙ ФАЙЛ (SRS-DB-009, PostgreSQL: новое значение ENUM исторически недостижимо в той же
-- транзакции, где оно ДОБАВЛЕНО, — нельзя ADD VALUE и в этой же транзакции использовать значение
-- где-либо ещё). ОГРАНИЧЕНИЕ ИНСТРУМЕНТА (обнаружено при подготовке этой миграции, не домысел):
-- `drizzle-orm/pg-core/dialect.ts` `migrate()` оборачивает ВСЕ ожидающие миграции текущего
-- запуска `db:migrate` в ОДНУ `session.transaction(...)` (проверено чтением исходника пакета,
-- `node_modules/.pnpm/drizzle-orm@.../pg-core/dialect.cjs` строки 46-74) — инструмент НЕ
-- предоставляет директивы «выполнить этот файл вне транзакции» (упомянутая в
-- `0009_verification_status_add_revoked.sql` «директива disable-transaction» относится к другому,
-- более раннему механизму этой кодовой базы, не к самому drizzle-orm). PostgreSQL 12+ разрешает
-- `ALTER TYPE ... ADD VALUE` ВНУТРИ транзакционного блока — ограничение снято ТОЛЬКО в части
-- «не использовать новое значение в ТОЙ ЖЕ транзакции»; этот файл не использует новое значение
-- нигде — атомарность одного `db:migrate`-запуска этому не мешает технически. Отдельный файл
-- сохранён (а) ради организационной изоляции (git-история, целевой откат), (б) чтобы значение
-- было безопасно использовать в СЛЕДУЮЩЕМ отдельном `db:migrate`-запуске (после того, как это
-- значение уже закоммичено предыдущим запуском) — практический смысл SRS-DB-009 для этого
-- инструмента именно в такой изоляции по запускам, а не в синтаксисе одного файла.
--
-- Идемпотентность — `ADD VALUE IF NOT EXISTS` (PG 9.6+), тот же синтаксис, что уже применён
-- ЭТОЙ кодовой базой в `0010_otp_purpose_add_onboarding_contact.sql`. ПРИМЕЧАНИЕ: у файла 0010
-- есть комментарий `-- disable-transaction` — проверено (чтением `apps/api/src/infrastructure/
-- database/migrate.ts` — тонкий враппер над `drizzle-orm`, без какого-либо парсинга комментариев
-- миграций), что этот комментарий НИКАК не влияет на фактическое поведение `drizzle-orm`
-- (комментарий из другого инструмента миграций, семантика которого здесь не реализована) —
-- foundIssue (документация вводит в заблуждение), не воспроизводится в этом файле намеренно.
-- =====================================================================================

ALTER TYPE "audit_action_category" ADD VALUE IF NOT EXISTS 'cash_reconciliation_discrepancy';
