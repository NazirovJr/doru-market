-- Обратная миграция 0024_i18n_overrides_review_status.
--
-- ОТЛИЧИЕ от DoD-текста DTJ-103 («down — ALTER TABLE i18n_overrides DROP COLUMN
-- review_status»): та формулировка предполагала уже существующую таблицу
-- (владелец — другая, более ранняя миграция). На момент реализации таблицы не
-- было нигде (см. комментарий в 0024_i18n_overrides_review_status.sql) — эта
-- миграция завела её ЦЕЛИКОМ, поэтому полный откат обязан удалить именно то,
-- что создал up-скрипт: таблицу целиком, а не только колонку (иначе down не
-- является инверсией up — в БД осталась бы таблица, которую 0024 не должна
-- была „наследовать" от несуществующей более ранней миграции).
DROP TABLE IF EXISTS i18n_overrides;
