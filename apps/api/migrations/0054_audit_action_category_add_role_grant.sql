-- ALTER TYPE audit_action_category ADD VALUE 'role_grant': GrantPlatformRoleUseCase пишет
-- audit_log с этой категорией при выдаче платформенной роли (super_admin/support_agent) —
-- значение отсутствует и в исходном списке (0034_support_tickets_audit_log.sql), и в
-- последующем расширении (0043_audit_action_category_cash_reconciliation.sql).
--
-- ОТДЕЛЬНЫЙ ФАЙЛ, ВНЕ ТРАНЗАКЦИИ ADD VALUE + использования значения (SRS-DB-009) — тот же
-- приём и то же документированное ограничение инструмента, что уже зафиксировано
-- 0043_audit_action_category_cash_reconciliation.sql (drizzle-orm `migrate()` оборачивает
-- миграции одного запуска `db:migrate` в одну транзакцию; PostgreSQL 12+ разрешает
-- `ALTER TYPE ... ADD VALUE` внутри транзакционного блока, но не разрешает использовать
-- НОВОЕ значение в ТОЙ ЖЕ транзакции, где оно добавлено — см. JSDoc 0043 для полного разбора,
-- не повторяется здесь). Этот файл значение не использует, только добавляет — безопасен
-- сам по себе, а `GrantPlatformRoleUseCase` использует его уже в следующем запуске.
--
-- Идемпотентность — `ADD VALUE IF NOT EXISTS` (PG 9.6+), тот же синтаксис, что 0043.
-- =====================================================================================

ALTER TYPE "audit_action_category" ADD VALUE IF NOT EXISTS 'role_grant';
