-- =====================================================================================
-- 0027_orders_cash_never_escrow.sql — EP-09, решение CTO (волна 6). D-25, последний рубеж.
-- =====================================================================================
-- D-25 — центральное денежное решение эпика: наличный заказ (`cash_courier`) переходит в
-- `confirmed` СИНХРОННО в `Order.create()` и НИКОГДА не наблюдается в `pending_payment` или
-- `paid_escrow`. Эскроу для наличных не создаётся вовсе: `paid_escrow` достижим только из
-- `pending_payment` по подписанному вебхуку банка (SRS-DOM-089).
--
-- До этой миграции D-25 держался ИСКЛЮЧИТЕЛЬНО на коде: машина состояний (DTJ-222), явный
-- guard в `Order.markPaidEscrow()` и валидатор `Order.restore()` (DTJ-221). Все три слоя
-- проверены и работают, но защищают ровно один путь записи — доменный. Любой другой путь к
-- таблице (сырой SQL из репозитория, админский скрипт, дата-миграция, будущий сервис,
-- написанный в обход агрегата) обошёл бы их молча.
--
-- Цена такой ошибки — не «неверная строка в таблице»: заказ в `paid_escrow` утверждает, что
-- деньги клиента лежат в эскроу. Для наличного заказа их там нет и быть не может. Дальше по
-- пайплайну на этот статус опирается расчёт с аптекой и возвраты (EP-11), то есть платформа
-- начнёт выплачивать по несуществующему платежу.
--
-- Почему CHECK, хотя `0023_orders_cart.sql` явно отказывается проверять переходы в БД:
-- отказ там касается ГРАФА переходов — это действительно домен, и в CHECK он не выражается
-- (нужно предыдущее состояние строки). Здесь же инвариант — предикат на ОДНОЙ строке, без
-- какого-либо знания об истории: сочетание `cash_courier` + эскроу-статус невозможно в любой
-- момент времени. Это тот же класс, что уже существующий `chk_orders_total_matches_sum`,
-- который сам себя описывает как «последний рубеж защиты, не источник истины».
--
-- Источник истины остаётся доменом: constraint не заменяет проверки в коде и не должен
-- перехватываться как бизнес-ошибка — его срабатывание означает дефект, а не действие
-- пользователя.
--
-- Применение безопасно без `NOT VALID`: перед созданием проверено, что нарушающих строк нет
-- ни в одной из баз (`dorutj_test`, `dorutj_test2`, `dorutj_test3` — 0 нарушений).
-- =====================================================================================

-- Идемпотентно: `ALTER TABLE ... ADD CONSTRAINT IF NOT EXISTS` в Postgres не существует,
-- поэтому повторное применение гасится перехватом `duplicate_object` — тот же приём, что в
-- `0028_orders_payments_extensions.sql`. Без этого повторный прогон раннера на базе, где
-- констрейнт уже есть, падает и блокирует ВСЕ последующие миграции.
DO $$ BEGIN
    ALTER TABLE orders
        ADD CONSTRAINT chk_orders_cash_never_escrow
        CHECK (payment_method <> 'cash_courier' OR status NOT IN ('pending_payment', 'paid_escrow'));
EXCEPTION
    WHEN duplicate_object THEN NULL;
END $$;

COMMENT ON CONSTRAINT chk_orders_cash_never_escrow ON orders IS
    'D-25 (SRS-ORD-027/028): cash_courier никогда не находится в pending_payment/paid_escrow. '
    'Структурный инвариант на одной строке — последний рубеж под доменными проверками '
    'Order.create()/markPaidEscrow()/restore(), а НЕ источник истины. Срабатывание = дефект кода.';
