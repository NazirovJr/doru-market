-- Номер: следующий свободный по `ls apps/api/migrations/` на момент создания файла —
-- занято по `0034_support_tickets_audit_log.sql` включительно (параллельный поток, не мой).
--
-- НЕ в буквальном `files_owned` DTJ-245 (`refund-order.use-case.ts`/`refund-facade.adapter.ts`)
-- — заведена по необходимости, тот же класс дополнения, что `escrow-ledger-repository.port.ts`
-- (DTJ-240) сверх своего буквального files_owned.
--
-- Задача: `escrow_ledger` — append-only (SRS-DOM-031), без `update`/`delete` в порту
-- (компиляционная гарантия DTJ-240) — «полный рефанд заказа происходит не более одного раза»
-- НЕ было выражено НИКАК на уровне БД: два конкурентных запроса на возврат одного и того же
-- `orderId` могли записать ДВЕ строки `refunded_to_customer`, удвоив сумму возврата.
--
-- Решение — ЧАСТИЧНЫЙ уникальный индекс: `UNIQUE(order_id) WHERE entry_type =
-- 'refunded_to_customer'`. Не блокирует НИКАКОЙ другой `entry_type` (несколько `hold_created`/
-- `adjustment`-записей на заказ остаются легальны, SRS-DOM-034/035) — сужен ИМЕННО до
-- инварианта «полный возврат — не более одного раза на заказ» (SRS-ORD-029: возврат либо
-- полный, либо его нет; частичный возврат — EP-11, другой `entry_type`).
--
-- Почему НЕ advisory-лок/транзакция вокруг `PaymentProvider.refund()`: живой прогон
-- `Promise.all` (10 конкурентных `refundFull()`) с транзакцией, держащей соединение пула на
-- время вызова провайдера (который САМ делает независимый запрос к БД через ТОТ ЖЕ пул),
-- воспроизвёл тот же класс тупика, что описан в задании раздел «Жёсткие правила» п.2 (20
-- соединений застряли на `begin`) — при `pool.max=10` и 10 конкурентных вызовов, 9 блокируются
-- на получении лока, оставляя недостаточно свободных соединений для внутреннего запроса
-- провайдера у активного держателя лока. Уникальный индекс — атомарная гарантия БД без
-- удержания транзакции/соединения через внешний вызов: `PaymentProvider.refund()` вызывается
-- СВОБОДНО (его собственная идемпотентность через `payment_operations.idempotency_key`
-- защищает от второго реального возврата у банка), финальная запись в ledger — одна короткая
-- `INSERT`, конфликт которой (`23505`) `RefundOrderUseCase` перехватывает как безопасный
-- «уже возвращено конкурентным вызовом», не как ошибку.
--
-- Применение безопасно без `NOT VALID`: перед созданием проверено — дублей `refunded_to_
-- customer` по `order_id` нет ни на одной тестовой базе (таблица пуста до первого рефанда).
-- =====================================================================================
CREATE UNIQUE INDEX IF NOT EXISTS ux_escrow_ledger_refunded_once
    ON escrow_ledger (order_id)
    WHERE entry_type = 'refunded_to_customer';

COMMENT ON INDEX ux_escrow_ledger_refunded_once IS
    'DTJ-245, SRS-ORD-029: не более одной записи refunded_to_customer на заказ (полный возврат '
    '— не более одного раза). Не ограничивает другие entry_type (append-only остаётся честным '
    'для hold_created/platform_fee_captured/captured_to_pharmacy/partially_refunded/adjustment).';
