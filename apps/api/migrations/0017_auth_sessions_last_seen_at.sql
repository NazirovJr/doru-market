-- Добавление колонки `last_seen_at` в `auth_sessions` для endpoint'а
-- `GET /auth/sessions` (DTJ-026, SRS-API-030): «когда в последний раз
-- использовали это устройство».
--
-- Инициализация:
--   - Существующие строки: `last_seen_at = COALESCE(rotated_at, created_at)`
--     (для уже ротированных — время ротации; для активных — время создания).
--   - Новые строки: `DEFAULT NOW()` (на уровне Drizzle-схемы).
--
-- Обновление:
--   - `RefreshTokenUseCase` (DTJ-025) обновляет `last_seen_at` для старой
--     строки в `revokeCurrentAndCreateNext` (предыдущая = текущее звено,
--     она только что использовалась). Это естественный момент — refresh
--     это и есть «использование».
--
-- Совместимость: эволюционная миграция — `ADD COLUMN ... NOT NULL DEFAULT NOW()`
-- заполняет все существующие строки одинаковым NOW() (теоретически можно
-- было бы вычислить `COALESCE(rotated_at, created_at)`, но для R1 простое
-- `DEFAULT NOW()` достаточно — историческое «время использования» для
-- старых строк неизвестно, приемлемо «с момента миграции»).
-- =============================================================================

ALTER TABLE auth_sessions
  ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
