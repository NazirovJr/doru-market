-- Номер сверен перед созданием: последняя применённая — 0029_payments.sql (idx 31,
-- meta/_journal.json), 0025 намеренно пропущен (D-EP09-33) — следующий свободный 0030.
--
-- BEST-EFFORT (тикет DTJ-240, раздел «Риски и подводные камни»): на момент написания этого
-- файла `app_role` — общая инфраструктура ролей БД (SRS-DB-030), которую ни один эпик ещё не
-- создал (проверено `SELECT rolname FROM pg_roles WHERE rolname = 'app_role'` — пусто на
-- момент этой миграции). Роль `test`, под которой прикладные миграции применяются на
-- назначенной этому тикету тестовой базе, не имеет `CREATEROLE` — создать `app_role` здесь
-- физически нельзя, и это НЕ входит в периметр тикета (DTJ-240 владеет только домен-
-- агрегатом/репозиторием `escrow_ledger`, не ролевой моделью БД целиком).
--
-- ОБНОВЛЕНИЕ (параллельная сессия, тот же день): `0031_app_role_privileges.sql` СОЗДАЁТ
-- `app_role` и делает то же самое REVOKE ЯВНО (плюс `ALTER DEFAULT PRIVILEGES` — покрывает и
-- будущие append-only таблицы). Этот файл НЕ удаляется и не переписывается вслед за 0031
-- (диск — истина, чужую миграцию не трогаем): после применения ОБОИХ файлов по порядку блок
-- ниже становится дважды подтверждающим no-op'ом (0031 уже отозвал права до того, как этот
-- файл успел бы что-то сделать при повторном прогоне) — безопасно, идемпотентно, не конфликтует.
--
-- Блок ниже УСЛОВНЫЙ: применяет GRANT/REVOKE, ТОЛЬКО если роль `app_role` существует — иначе
-- no-op. Отсутствие роли на конкретной базе НЕ считается ошибкой этой миграции.
--
-- Идемпотентно (правило 11 AGENTS.md, урок волны 6 — CTO-заметка в
-- 0027_orders_cash_never_escrow.sql): GRANT/REVOKE в PostgreSQL сами по себе идемпотентны
-- (повторное GRANT/REVOKE тех же прав не бросает), `IF EXISTS`-проверка роли защищает
-- ТОЛЬКО от отсутствия роли — файл безопасно применяется дважды подряд.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_role') THEN
    GRANT INSERT, SELECT ON escrow_ledger TO app_role;
    REVOKE UPDATE, DELETE ON escrow_ledger FROM app_role;
  END IF;
END $$;
