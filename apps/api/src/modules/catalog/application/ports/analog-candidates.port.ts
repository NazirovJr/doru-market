/**
 * Порт `AnalogCandidatesRepository` (DTJ-100, EP-07, R1).
 *
 * SQL-предфильтр кандидатов аналогов по МНОЖЕСТВУ действующих веществ +
 * форме выпуска + фильтрам видимости/безопасности (опубликован, не
 * психотропный/наркотический). Это первый рубеж защиты перед тяжёлым
 * доменным решением `AnalogEquivalenceService.isAnalog()` (DTJ-099), которое
 * уточняет дозировку для каждого кандидата в памяти.
 *
 * **Зачем отдельный порт, а не метод `CatalogRepository`?**
 *   1. Контракт возвращает только `medicineId[]` (а не полные `MedicineRecord`)
 *      — для скорости: полные агрегаты подгружает второй шаг DTJ-101 через
 *      `CatalogRepository.findMedicinesByIds`, избегая дублирования пути загрузки.
 *   2. SQL использует корреллированный `array_agg` + `array_equality` (SRS-CAT-043) —
 *      специфичная логика предфильтра, которая не нужна другим use case'ам каталога.
 *   3. Точная семантика «одинаковое множество веществ + форма» — осознанно
 *      отличается от доменного решения в DTJ-099 (которое дополнительно проверяет
 *      эквивалентность дозировки через `Dosage.isEquivalentTo`). Это **расхождение
 *      SQL-предфильтра и доменного правила — сознательное разделение «быстрая грубая
 *      выборка» / «точное решение в DTJ-099», не дефект** (см. SRS-CAT-043).
 *
 * **Граница модуля.** Порт читает ТОЛЬКО таблицы `medicines` и
 * `medicine_substances` — обе catalog-owned (`02-CLEAN-ARCHITECTURE-AND-CODE.md`
 * §1.1 запрещает только МЕЖМОДУЛЬНЫЕ прямые джойны; внутри своего модуля
 * прямой SQL к своим таблицам разрешён без исключений).
 *
 * **Бюджет.** Возвращает ≤ `limit` записей; типичный вызов — `limit = 50`
 * (SRS-CAT-061 «O(50), не O(N)»). Константа `ANALOG_CANDIDATES_LIMIT`
 * объявляется вызывающим (DTJ-101), не этим файлом.
 *
 * @see docs/spec/20-module-catalog-search.md (SRS-CAT-042/043/061)
 * @see docs/spec/10-domain-model.md (SRS-DOM-157/158)
 */

/** DI-токен NestJS для `AnalogCandidatesRepository` (D-27: единый Symbol на пакет). */
export const ANALOG_CANDIDATES_REPOSITORY = Symbol.for(
  '@dorutj/catalog/analog-candidates-repository',
)

/**
 * Контракт порта (DTJ-100).
 *
 * Метод ВСЕГДА возвращает массив id (возможно пустой). Исключение НЕ бросает —
 * отсутствие кандидатов — нормальная ситуация (например, препарат с уникальным
 * составом). Решение о финальном списке аналогов принимает use case (DTJ-101).
 */
export interface AnalogCandidatesRepository {
  /**
   * Возвращает `medicineId[]` препаратов, удовлетворяющих ВСЕМ условиям:
   *   - `id != referenceMedicineId` (исключаем сам референс);
   *   - `is_published = true` (черновики не утекают в публичный API);
   *   - `control_category NOT IN ('psychotropic', 'narcotic')` — defense-in-depth,
   *     SRS-DOM-157, на случай если use case пропустит фильтр;
   *   - та же `dosage_form_class`, что у референса;
   *   - МНОЖЕСТВО `substance_id` ИДЕНТИЧНО (а не подмножество/пересечение) —
   *     сравнение через `array_agg ... ORDER BY` (SRS-CAT-043, TC-CAT-030).
   *
   * @param referenceMedicineId — UUID референсного препарата
   * @param limit — максимальное число кандидатов (`<= 0` трактуется как `1`,
   *   огромные значения НЕ клампятся — вызывающий (DTJ-101) передаёт `ANALOG_CANDIDATES_LIMIT`).
   *   Контракт НЕ ограничивает максимальное значение сверху — это политика
   *   вызывающего. Адаптер доверяет входному `limit` как параметризованному SQL.
   *
   * Поведение для edge-кейсов:
   *   - `referenceMedicineId` не существует → пустой массив (а не ошибка);
   *     корреллированный подзапрос `target_substances` вернёт пустой набор,
   *     `array_agg = NULL` (от пустого набора) никогда не совпадёт ни с одной
   *     строкой правой части (по SQL-семантике `=` с NULL), что и есть
   *     желаемое поведение (осознанное, не дефект — см. SRS-CAT-043).
   *   - `referenceMedicineId` существует, но не имеет ни одного вещества —
   *     пустой массив (аналогично: пустой `target_substances` → нет совпадений).
   *     Фиксируется unit/интеграционным тестом как осознанное поведение.
   */
  findCandidates(
    referenceMedicineId: string,
    limit: number,
  ): Promise<readonly string[]>
}