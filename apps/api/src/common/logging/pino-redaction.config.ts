/**
 * `pino`-редактор чувствительных полей (EP-16, DTJ-375, SRS-ADM-044/063) — генерирует
 * `redact.paths` ИЗ ЕДИНОГО списка `SENSITIVE_FIELD_NAMES` (`@dorutj/contracts`,
 * `packages/contracts/src/sensitive-fields.ts`), НЕ отдельным списком путей: `pino` и
 * `audit_log` (`../audit/infrastructure/audit-log.repository.ts`) обязаны читать ОДИН источник
 * (риск расхождения списков, C15 AGENTS.md).
 *
 * Движок редактора `pino@^10.3.1` (`01-TECH-BASELINE.md`) — `@pinojs/redact`, тот же синтаксис
 * путей, что `fast-redact`: wildcard `*` покрывает РОВНО ОДИН уровень вложенности, рекурсивного
 * `**`-паттерна на произвольную глубину НЕТ. Поэтому на каждое имя поля заводятся ДВЕ записи:
 *  - `{field}` — поле лежит на верхнем уровне логируемого объекта;
 *  - `*.{field}` — поле лежит на один уровень глубже (типичный случай: `{ user: { apiKey } }`).
 *
 * Более глубокая вложенность путями `pino` НЕ покрывается — это ОСОЗНАННОЕ ограничение движка
 * редактора, а не пропуск: правило §13 хендбука («никогда не логируй» секреты) требует не
 * логировать секрет целиком, а не полагаться на редактор для сколь угодно вложенных объектов.
 * Асимметрично `audit_log`, где `maskSensitiveFields` (`@dorutj/contracts`) рекурсирует НА ЛЮБУЮ
 * глубину — это осознанное решение Tech Lead (см. «Риски» `DTJ-375`): лог не может «отказаться
 * писаться» и не должен падать из-за случайного секрета произвольной вложенности, а `audit_log`
 * — неизменяемый журнал, для которого фиксированная глубина двух рубежей (домен + repository)
 * достаточна, так как форма `metadata` контрактно ограничена (`before`/`after`/`extra`).
 */
import { SENSITIVE_FIELD_NAMES } from '@dorutj/contracts'

/** Строится один раз при конфигурации логгера (`root-logger.ts`), не на каждый вызов лога. */
export function buildSensitiveFieldRedactPaths(): string[] {
  return SENSITIVE_FIELD_NAMES.flatMap((field) => [field, `*.${field}`])
}
