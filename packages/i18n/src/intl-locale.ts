/**
 * Маппинг внутреннего кода локали платформы на реальный тег BCP-47 для семейства `Intl.*`.
 *
 * **Зачем это существует.** Внутренний код таджикской локали в проекте — `'tj'` (см. `Locale` в
 * `use-t.ts`, он же лежит в БД в `i18n_overrides.locale` и ходит в `Accept-Language`). В реестре
 * языков BCP-47/ISO 639 тега `'tj'` НЕ существует — код таджикского языка `'tg'`. Для
 * незарегистрированного тега поведение `Intl` не определено спецификацией и остаётся на усмотрение
 * реализации, а на практике оно ещё и молчаливое:
 *
 *     new Intl.NumberFormat('tj').resolvedOptions().locale  // → 'en-US'  (Node 24 / ICU 78)
 *     new Intl.NumberFormat('tg').resolvedOptions().locale  // → 'tg'
 *
 * То есть `Intl` не падает и не предупреждает — он отдаёт американское форматирование, выдавая его
 * за таджикское: точка вместо запятой в дробной части, американский порядок дат, чужие правила
 * разрядов. `'tj'` — локаль платформы ПО УМОЛЧАНИЮ (`SRS-UX-027`), так что это поведение получал бы
 * каждый пользователь, ничего не переключавший.
 *
 * Хуже того, откат для незарегистрированного тега различается между средами: Node/ICU (где идут
 * тесты) и Chromium (где работает приложение) дают РАЗНЫЙ результат. Тест мог быть зелёным при
 * неверном выводе у пользователя — обнаружено на сдаче DTJ-104 живым прогоном в браузере, а не
 * рассуждением.
 *
 * **Почему не переименовать `'tj'` в `'tg'` целиком.** Внутренний код уже зашит в данные
 * (`i18n_overrides.locale`), в контракт API и в имена файлов словарей. Переименование — это
 * миграция данных плюс смена контракта ради косметики. Дешевле и надёжнее держать ОДНУ границу
 * перевода — здесь.
 *
 * **Правило: в `Intl.*` никогда не передаётся `Locale` напрямую — только `toIntlLocale(locale)`.**
 * Нарушение не даёт ни ошибки, ни предупреждения, поэтому ловится оно только на ревью и вот этим
 * файлом как единственной точкой правды.
 */
import type { Locale } from './use-t.js'

const INTL_LOCALE_BY_APP_LOCALE: Readonly<Record<Locale, string>> = {
  tj: 'tg',
  ru: 'ru',
  en: 'en',
}

/** Тег BCP-47, пригодный для `Intl.NumberFormat`/`DateTimeFormat`/`Collator` и прочих. */
export function toIntlLocale(locale: Locale): string {
  return INTL_LOCALE_BY_APP_LOCALE[locale]
}
